/**
 * Builds supabase/dev-bootstrap-combined.sql — run migrations on an empty dev DB
 * in one paste (Supabase Dashboard → SQL Editor → New query).
 *
 *   npm run db:bootstrap-file
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const supabaseDir = path.join(__dirname, '..', 'supabase')
const outFile = path.join(supabaseDir, 'dev-bootstrap-combined.sql')

const FILES = [
  'migration.sql',
  'migration-v2.sql',
  'migration-v3-onboarding.sql',
  'migration-v4-submitted.sql',
  'migration-v5-leaderboard.sql',
  'migration-v6-delete-own-data.sql',
  'migration-v7-streak-bonus.sql',
  'migration-v8-penalty-pot-sync.sql',
  'migration-v9-submitted-only-scoring.sql',
  'migration-v10-streak-travel-rules.sql',
  'migration-v11-enable-realtime.sql',
  'migration-v12-badges.sql',
  'migration-v13-badges-day-one-and-sync.sql',
  'migration-v14-badge-day-one-trigger.sql',
  'migration-v15-hidden-badges.sql',
  'migration-v16-badge-collector-bonus.sql',
  'migration-v17-badge-gating-challenge-start.sql',
  'migration-v18-penalty-pot-resync.sql',
  'migration-v19-penalty-trigger-rls.sql',
  'migration-v20-hidden-badges-after-day90.sql',
  'migration-v21-checkin-before-tasks.sql',
  'storage.sql',
]

let out = `-- ShipShape90 — combined bootstrap for an EMPTY database
-- Generated by: npm run db:bootstrap-file
-- Apply: Supabase Dashboard → SQL Editor → paste this file → Run.
-- Do NOT use reset-all-data.sql for first-time setup (that wipes data/users).

`

for (const name of FILES) {
  const p = path.join(supabaseDir, name)
  if (!fs.existsSync(p)) {
    console.error(`Missing: ${p}`)
    process.exit(1)
  }
  out += `\n-- ========== ${name} ==========\n\n`
  out += fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n')
  if (!out.endsWith('\n')) out += '\n'
}

fs.writeFileSync(outFile, out, 'utf8')
console.log(`Wrote ${outFile} (${FILES.length} files, ${out.length} bytes)`)
